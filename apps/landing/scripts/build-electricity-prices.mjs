#!/usr/bin/env node
// Refresh script for src/lib/calculators/data/electricityPrices.ts.
//
// Source: Eurostat, "Electricity prices for household consumers - bi-annual data" (dataset
// nrg_pc_204), consumption band DC (2 500 to 4 999 kWh a year), all taxes and levies included,
// in euro per kWh, for Portugal and the European Union (27 countries, from 2020), half-yearly.
// https://ec.europa.eu/eurostat/databrowser/view/nrg_pc_204/
//
// Usage, from apps/landing (needs network; Node 18+ for fetch):
//
//   node scripts/build-electricity-prices.mjs [--from-file <response.json>] [--date YYYY-MM-DD]
//
// --from-file reads a saved API response instead of calling the API (for checks); --date sets
// the "fetched on" stamp (defaults to today, UTC). Only half-years in which both Portugal and the
// EU have a value are kept. The generated module is committed: the page never calls Eurostat.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SOURCE = {
  name: "Eurostat, Electricity prices for household consumers - bi-annual data (nrg_pc_204)",
  url: "https://ec.europa.eu/eurostat/databrowser/view/nrg_pc_204/",
  dataset: "nrg_pc_204",
  band: "KWH2500-4999",
  tax: "I_TAX",
};

export const API_URL =
  "https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/nrg_pc_204" +
  "?format=JSON&lang=EN&geo=PT&geo=EU27_2020&nrg_cons=KWH2500-4999&tax=I_TAX&currency=EUR&unit=KWH";

const PERIOD = /^(\d{4})-S([12])$/;

/** Offset of a cell in the JSON-stat value array, given one category index per dimension. */
function offsetOf(json, positions) {
  let offset = 0;
  let stride = 1;
  for (let i = json.id.length - 1; i >= 0; i--) {
    offset += (positions[json.id[i]] ?? 0) * stride;
    stride *= json.size[i];
  }
  return offset;
}

/**
 * Eurostat JSON-stat response to [{ period, pt, eu }] in euro per kWh, oldest first, for the
 * half-years where both values exist. Throws on anything that is not the expected cut.
 */
export function deriveRows(json) {
  if (!json || json.class !== "dataset" || !Array.isArray(json.id) || !json.value) {
    throw new Error("Not a JSON-stat dataset");
  }
  const dim = (name) => json.dimension?.[name]?.category?.index;
  const geo = dim("geo");
  const time = dim("time");
  if (!geo || geo.PT === undefined || geo.EU27_2020 === undefined || !time) {
    throw new Error("The response must hold Portugal (PT) and EU27_2020 over time");
  }
  for (const [name, expected] of [
    ["nrg_cons", SOURCE.band],
    ["tax", SOURCE.tax],
    ["unit", "KWH"],
    ["currency", "EUR"],
  ]) {
    const categories = Object.keys(dim(name) ?? {});
    if (categories.length !== 1 || categories[0] !== expected) {
      throw new Error(`Expected ${name} to be only ${expected}, got ${categories.join(",") || "nothing"}`);
    }
  }
  const valueAt = (geoKey, periodIndex) => {
    const value = json.value[offsetOf(json, { geo: geo[geoKey], time: periodIndex })];
    return typeof value === "number" ? value : undefined;
  };
  const rows = [];
  for (const [period, index] of Object.entries(time)) {
    if (!PERIOD.test(period)) throw new Error(`Unexpected period ${period}`);
    const pt = valueAt("PT", index);
    const eu = valueAt("EU27_2020", index);
    if (pt === undefined || eu === undefined) continue;
    if (!(pt > 0 && pt < 2 && eu > 0 && eu < 2)) throw new Error(`Implausible price in ${period}`);
    rows.push({ period, pt, eu });
  }
  rows.sort((a, b) => a.period.localeCompare(b.period));
  if (rows.length < 10) throw new Error(`Only ${rows.length} half-years: refusing to write`);
  return rows;
}

export function renderModule(rows, { updatedOn, fetchedOn }) {
  const lines = rows.map((r) => `  [${JSON.stringify(r.period)}, ${r.pt}, ${r.eu}],`);
  return `// Generated by scripts/build-electricity-prices.mjs. Do not edit by hand: rerun the script.
//
// Household electricity prices, Portugal and the European Union, half-yearly, in euro per kWh with
// all taxes and levies included, for annual consumption of 2 500 to 4 999 kWh (Eurostat band DC).
// The page reads this module only: it never calls Eurostat. Educational data.

export const ELECTRICITY_PRICES_SOURCE = {
  name: ${JSON.stringify(SOURCE.name)},
  url: ${JSON.stringify(SOURCE.url)},
  dataset: ${JSON.stringify(SOURCE.dataset)},
  band: "2 500 to 4 999 kWh a year (band DC)",
  /** When Eurostat last updated the dataset (the response's own stamp). */
  updatedOn: ${JSON.stringify(updatedOn)},
  /** When this file was generated from the API. */
  fetchedOn: ${JSON.stringify(fetchedOn)},
  /** Bump when the derivation changes, not when new half-years are appended. */
  version: 1,
  firstPeriod: ${JSON.stringify(rows[0].period)},
  lastPeriod: ${JSON.stringify(rows[rows.length - 1].period)},
} as const;

/** One half-year: [period "YYYY-S1" or "YYYY-S2", Portugal EUR/kWh, EU-27 average EUR/kWh]. */
export type ElectricityPriceRow = readonly [period: string, portugal: number, eu: number];

export const ELECTRICITY_PRICES: readonly ElectricityPriceRow[] = [
${lines.join("\n")}
];
`;
}

async function main() {
  const args = process.argv.slice(2);
  const option = (name) => {
    const at = args.indexOf(name);
    return at === -1 ? undefined : args[at + 1];
  };
  const fetchedOn = option("--date") ?? new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(fetchedOn)) throw new Error("--date must be YYYY-MM-DD");
  const file = option("--from-file");
  let json;
  if (file) json = JSON.parse(readFileSync(file, "utf8"));
  else {
    const response = await fetch(API_URL);
    if (!response.ok) throw new Error(`Eurostat answered ${response.status}`);
    json = await response.json();
  }
  const updatedOn = typeof json.updated === "string" ? json.updated.slice(0, 10) : fetchedOn;
  const rows = deriveRows(json);
  const out = fileURLToPath(new URL("../src/lib/calculators/data/electricityPrices.ts", import.meta.url));
  writeFileSync(out, renderModule(rows, { updatedOn, fetchedOn }));
  console.log(`Wrote ${rows.length} half-years (${rows[0].period} to ${rows.at(-1).period}) to ${out}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
