#!/usr/bin/env node
// Refresh script for src/lib/calculators/data/euribor.ts.
//
// Source: Banco de Portugal, BPstat (https://bpstat.bportugal.pt), "Money market statistics:
// Reference interest rate - EURIBOR", monthly averages. BPstat disseminates these free of charge
// as a public service; its API is open. It publishes monthly averages only, no daily fixings, so
// the page shows monthly averages and says so. EMMI owns the Euribor trademark and restricts
// redistributing its own daily data, which is why this page never shows daily values.
//
//   series 13168436  Euribor 3 months - monthly average
//   series 13168438  Euribor 6 months - monthly average
//   series 13168437  Euribor 1 year  - monthly average
//
// Usage (Node 18+, network access; run from apps/landing):
//
//   node scripts/build-euribor.mjs            fetch from BPstat and write the module
//   node scripts/build-euribor.mjs <file.json> use a saved JSON-stat response instead of fetching

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SOURCE = {
  name: "Banco de Portugal, BPstat: Euribor monthly averages",
  url: "https://bpstat.bportugal.pt/conteudos/quadros/2599",
};
export const DATASET_URL =
  "https://bpstat.bportugal.pt/data/v1/domains/22/datasets/2829cb9155cb4f6ba6906db6b204c4bc/?lang=EN&series_ids=13168436,13168438,13168437";
/** Series id by tenor in months. */
export const SERIES = { 3: 13168436, 6: 13168438, 12: 13168437 };
export const FIRST_MONTH = "2000-01";

const round = (value) => Number(value.toFixed(4));

/**
 * BPstat JSON-stat response to [{ month: "YYYY-MM", m3, m6, m12 }] (percent, 4 decimals) from
 * FIRST_MONTH. Throws when a series is missing, a month has no value or the months differ.
 */
export function parseBpstat(json) {
  const dates = json.dimension?.reference_date?.category?.index;
  const tenors = json.dimension?.["46"]?.category?.index;
  if (!Array.isArray(dates) || !Array.isArray(tenors)) throw new Error("Unexpected BPstat response shape");
  const labels = json.dimension["46"].category.label;
  const columns = { m3: "3 months", m6: "6 months", m12: "1 year" };
  const position = {};
  for (const [key, label] of Object.entries(columns)) {
    const id = tenors.find((candidate) => labels[candidate] === label);
    if (id === undefined) throw new Error(`Missing tenor ${label}`);
    position[key] = tenors.indexOf(id);
  }
  if (json.value.length !== tenors.length * dates.length) throw new Error("Value count does not match the dimensions");
  const rows = [];
  dates.forEach((date, i) => {
    const month = date.slice(0, 7);
    if (month < FIRST_MONTH) return;
    const row = { month };
    for (const key of Object.keys(columns)) {
      const value = json.value[position[key] * dates.length + i];
      if (typeof value !== "number") throw new Error(`No ${key} value for ${month}`);
      row[key] = round(value);
    }
    rows.push(row);
  });
  rows.forEach((row, i) => {
    if (i > 0) {
      const [y, m] = rows[i - 1].month.split("-").map(Number);
      const next = m === 12 ? `${y + 1}-01` : `${y}-${String(m + 1).padStart(2, "0")}`;
      if (row.month !== next) throw new Error(`Gap before ${row.month}`);
    }
  });
  if (rows.length === 0) throw new Error("No rows");
  return rows;
}

export function renderModule(rows, fetchedOn) {
  const lines = rows.map((r) => `  ["${r.month}", ${r.m3}, ${r.m6}, ${r.m12}],`);
  return `// Generated by scripts/build-euribor.mjs. Do not edit by hand: rerun the script.
//
// Monthly averages of the Euribor 3, 6 and 12 month rates, in percent, from Banco de Portugal's
// BPstat. Monthly averages only: no daily fixings. Educational data, not a quote.

export const EURIBOR_SOURCE = {
  name: ${JSON.stringify(SOURCE.name)},
  url: ${JSON.stringify(SOURCE.url)},
  /** The day the data was fetched, YYYY-MM-DD. */
  fetchedOn: ${JSON.stringify(fetchedOn)},
  firstMonth: ${JSON.stringify(rows[0].month)},
  /** The latest month in the data: an average over that whole month. */
  lastMonth: ${JSON.stringify(rows.at(-1).month)},
} as const;

/** One month: [YYYY-MM, 3 month %, 6 month %, 12 month %], each the monthly average. */
export type EuriborRow = readonly [month: string, m3: number, m6: number, m12: number];

export const EURIBOR_HISTORY: readonly EuriborRow[] = [
${lines.join("\n")}
];
`;
}

async function main() {
  const file = process.argv[2];
  const json = file
    ? JSON.parse(readFileSync(file, "utf8"))
    : await (async () => {
        const response = await fetch(DATASET_URL, { headers: { accept: "application/json" } });
        if (!response.ok) throw new Error(`BPstat answered ${response.status}`);
        return response.json();
      })();
  const rows = parseBpstat(json);
  const out = fileURLToPath(new URL("../src/lib/calculators/data/euribor.ts", import.meta.url));
  writeFileSync(out, renderModule(rows, new Date().toISOString().slice(0, 10)));
  console.log(`Wrote ${rows.length} months (${rows[0].month} to ${rows.at(-1).month}) to ${out}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
