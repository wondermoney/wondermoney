import { describe, expect, it } from "vitest";
import { aggregate, deriveDays, renderModule } from "../../../scripts/build-electricity-profiles.mjs";
import { quartersInLegalDay } from "./electricityCycles";

// The four header rows of E-REDES's Perfil_Consumo_Injeção_E-REDES_2026.xlsx, shortened.
const HEADER_ROWS = [
  ["Data", null, null, "RESP (MW)", "Perfis de Consumo e Injeção"],
  [null, null, null, null, "BTN A", "BTN B", "BTN C", "IP"],
  [],
  [],
];
// Its first data row (1 January 2026, 00:00 to 00:15): Excel day, Excel day, end label, RESP, A, B, C, IP.
const FIRST_ROW = [46023, 46023, "00:15", 5364.9806144, 0.021382, 0.0291422, 0.0360875, 0.0603584];
const EXCEL_DAY_2026_01_01 = 46023;

/** A whole 2026 in the file's layout, every quarter-hour the same share except the first. */
function year2026(): unknown[][] {
  const rows: unknown[][] = [...HEADER_ROWS, FIRST_ROW];
  const quarters = 35_040 - 1;
  const flat = (1000 - 0.021382) / quarters;
  const flatB = (1000 - 0.0291422) / quarters;
  const flatC = (1000 - 0.0360875) / quarters;
  for (let d = 0; d < 365; d++) {
    const date = new Date(Date.UTC(2026, 0, 1 + d));
    const count = quartersInLegalDay(2026, date.getUTCMonth() + 1, date.getUTCDate());
    for (let q = d === 0 ? 1 : 0; q < count; q++) {
      rows.push([EXCEL_DAY_2026_01_01 + d, EXCEL_DAY_2026_01_01 + d, "", 5000, flat, flatB, flatC, 0.05]);
    }
  }
  return rows;
}

describe("build-electricity-profiles", () => {
  it("checks the quarter-hours of each day, 92 and 100 on the clock-change days", () => {
    const days = deriveDays(year2026());
    expect(days).toHaveLength(365);
    expect(days[87]).toMatchObject({ key: "2026-03-29" });
    expect(days[87].values.C).toHaveLength(92);
    expect(days[297].values.C).toHaveLength(100);
    expect(days[0].values.C[0]).toBe(0.0360875);
  });

  it("splits each profile by schedule, cycle, month and period, summing to 1000", () => {
    const result = aggregate(deriveDays(year2026()));
    expect(result.year).toBe(2026);
    for (const profile of ["A", "B", "C"] as const) expect(result.totals[profile]).toBeCloseTo(1000, 6);
    // The published first quarter-hour (00:00 to 00:15 on 1 January) is valley in every cycle.
    const flatC = (1000 - 0.0360875) / 35_039;
    const january = result.periods.C.current.daily[0];
    // January, daily cycle in winter: 31 days x (16 peak, 40 shoulder, 40 valley quarter-hours).
    expect(january[0]).toBeCloseTo(31 * 16 * flatC, 6);
    expect(january[1]).toBeCloseTo(31 * 40 * flatC, 6);
    expect(january[2]).toBeCloseTo((31 * 40 - 1) * flatC + 0.0360875, 6);
    // Weekly cycle, January 2026: 22 weekdays, 5 Saturdays (28 shoulder quarter-hours), 4 Sundays.
    const weekly = result.periods.C.current.weekly[0];
    expect(weekly[0]).toBeCloseTo(22 * 20 * flatC, 6);
    expect(weekly[1]).toBeCloseTo((22 * 48 + 5 * 28) * flatC, 6);
  });

  it("rejects a file without the BTN columns, a short day or a year that does not sum to 1000", () => {
    expect(() => deriveDays([["Data"], [null, "BTN A", "BTN B"], [46023, 46023, 0.1, 0.1]])).toThrow(/BTN C/);
    const short = year2026();
    short.splice(10, 1);
    expect(() => deriveDays(short)).toThrow(/2026-01-01 has 95 quarter-hours/);
    const off = year2026();
    (off[5] as number[])[6] += 1;
    expect(() => aggregate(deriveDays(off))).toThrow(/BTN C sums to/);
    expect(() => aggregate(deriveDays(year2026()).slice(1))).toThrow(/364 days/);
  });

  it("renders a typed module with its source and date", () => {
    const text = renderModule(aggregate(deriveDays(year2026())), { downloadedOn: "2026-11-20", sha256: "abc" });
    expect(text).toContain("Generated by scripts/build-electricity-profiles.mjs");
    expect(text).toContain('downloadedOn: "2026-11-20"');
    expect(text).toContain("year: 2026,");
    expect(text).toContain("export const ELECTRICITY_PROFILE_PERIODS");
    expect(text).toMatch(/"2027": \{\n {6}daily: \[/);
  });
});
