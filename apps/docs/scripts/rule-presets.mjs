/**
 * Keep the Rules page's list of locale rule presets in step with the presets that ship.
 *
 * The presets are JSON files in `packages/shared/lib/rule-presets/`. This writes, in each docs
 * locale, the table of every preset's rules between the `rule-presets:start` and
 * `rule-presets:end` markers of `accounts-transactions/rules.mdx`, so the docs can never list a
 * rule the app does not install (or miss one it does). `--check` (run by `pnpm lint`) fails
 * instead of writing when a page is out of date.
 *
 *   node scripts/rule-presets.mjs          # rewrite the lists
 *   node scripts/rule-presets.mjs --check  # fail if they are stale
 *
 * Category names are the app's own (web `messages/<locale>/categories.json`); a preset that uses
 * a category missing below fails the script, so add its three names here.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const presetsDirectory = join(root, '..', '..', 'packages', 'shared', 'lib', 'rule-presets');
const page = (locale) => join(root, 'content', 'docs', locale, 'accounts-transactions', 'rules.mdx');

const START = '{/* rule-presets:start (generated by scripts/rule-presets.mjs; do not edit by hand) */}';
const END = '{/* rule-presets:end */}';

const CATEGORY_NAMES = {
  en: {
    ELECTRICITY: 'Electricity',
    FOOD_DELIVERY: 'Food delivery',
    FUEL: 'Fuel',
    GAS: 'Gas',
    GROCERIES: 'Groceries',
    HEALTH: 'Health',
    PUBLIC_TRANSPORT: 'Public Transport',
    STREAMING_SERVICES: 'Streaming Services',
    TV_PHONE_INTERNET: 'TV, Phone & Internet',
    VEHICLE_MAINTENANCE: 'Vehicle Maintenance',
    WATER: 'Water',
  },
  es: {
    ELECTRICITY: 'Electricidad',
    FOOD_DELIVERY: 'Comida a domicilio',
    FUEL: 'Combustible',
    GAS: 'Gas',
    GROCERIES: 'Supermercado',
    HEALTH: 'Salud',
    PUBLIC_TRANSPORT: 'Transporte público',
    STREAMING_SERVICES: 'Servicios de streaming',
    TV_PHONE_INTERNET: 'TV, teléfono e internet',
    VEHICLE_MAINTENANCE: 'Mantenimiento del vehículo',
    WATER: 'Agua',
  },
  pt: {
    ELECTRICITY: 'Eletricidade',
    FOOD_DELIVERY: 'Entrega de Comida',
    FUEL: 'Combustível',
    GAS: 'Gás',
    GROCERIES: 'Mercearia',
    HEALTH: 'Saúde',
    PUBLIC_TRANSPORT: 'Transportes públicos',
    STREAMING_SERVICES: 'Serviços de "Streaming"',
    TV_PHONE_INTERNET: 'TV, Telefone & Internet',
    VEHICLE_MAINTENANCE: 'Manutenção de veículos',
    WATER: 'Água',
  },
};

const COPY = {
  en: {
    columns: ['Rule', 'Description contains', 'Category', 'Merchant'],
    excludes: (values) => `but not ${values}`,
    heading: (name, code, count) => `### ${name} (\`${code}\`, ${count} rules)`,
    names: { en: 'United Kingdom and United States', 'es-ES': 'Spain', 'pt-BR': 'Brazil', 'pt-PT': 'Portugal' },
  },
  es: {
    columns: ['Regla', 'La descripción contiene', 'Categoría', 'Comercio'],
    excludes: (values) => `pero no ${values}`,
    heading: (name, code, count) => `### ${name} (\`${code}\`, ${count} reglas)`,
    names: { en: 'Reino Unido y Estados Unidos', 'es-ES': 'España', 'pt-BR': 'Brasil', 'pt-PT': 'Portugal' },
  },
  pt: {
    columns: ['Regra', 'A descrição contém', 'Categoria', 'Comerciante'],
    excludes: (values) => `mas não ${values}`,
    heading: (name, code, count) => `### ${name} (\`${code}\`, ${count} regras)`,
    names: { en: 'Reino Unido e Estados Unidos', 'es-ES': 'Espanha', 'pt-BR': 'Brasil', 'pt-PT': 'Portugal' },
  },
};

const ORDER = ['pt-PT', 'es-ES', 'pt-BR', 'en'];

const presets = readdirSync(presetsDirectory)
  .filter((name) => name.endsWith('.json'))
  .map((name) => JSON.parse(readFileSync(join(presetsDirectory, name), 'utf8')))
  .sort((a, b) => {
    const rank = (preset) => (ORDER.includes(preset.preset.code) ? ORDER.indexOf(preset.preset.code) : ORDER.length);
    return rank(a) - rank(b) || a.preset.code.localeCompare(b.preset.code);
  });

const failures = [];

/** Table cells: escape the pipe, and keep MDX from reading `<`, `{` or `*` as syntax. */
const cell = (value) => String(value).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/[<>{}*_]/g, (character) => `\\${character}`);
const quoted = (value) => `“${cell(value)}”`;

function render(locale) {
  const copy = COPY[locale];
  const sections = presets.map((preset) => {
    const { code } = preset.preset;
    const name = copy.names[code];
    if (!name) failures.push(`${locale}: no name for preset "${code}" in scripts/rule-presets.mjs.`);
    const rows = preset.rules.map((rule) => {
      const texts = rule.conditions.filter((condition) => condition.field === 'description' || condition.field === 'merchant');
      const contains = texts.filter((condition) => condition.operator !== 'not_contains').map((condition) => quoted(condition.value));
      const excludes = texts.filter((condition) => condition.operator === 'not_contains').map((condition) => quoted(condition.value));
      const category = rule.actions.find((action) => action.type === 'set_category')?.category?.system;
      const categoryName = category ? CATEGORY_NAMES[locale][category] : undefined;
      if (category && !categoryName) failures.push(`${locale}: no name for category "${category}" (preset ${code}) in scripts/rule-presets.mjs.`);
      const merchant = rule.actions.find((action) => action.type === 'set_merchant')?.merchant;
      const matching = [contains.join(', '), excludes.length > 0 ? copy.excludes(excludes.join(', ')) : ''].filter(Boolean).join(' ');
      return `| ${cell(rule.name)} | ${matching} | ${cell(categoryName ?? '—')} | ${merchant ? cell(merchant) : '—'} |`;
    });
    return [
      copy.heading(name ?? code, code, preset.rules.length),
      '',
      `| ${copy.columns.join(' | ')} |`,
      `| ${copy.columns.map(() => '---').join(' | ')} |`,
      ...rows,
    ].join('\n');
  });
  return [START, '', ...sections.flatMap((section) => [section, '']), END].join('\n');
}

const check = process.argv.includes('--check');

for (const locale of Object.keys(COPY)) {
  const path = page(locale);
  const text = readFileSync(path, 'utf8');
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    failures.push(`${relative(root, path)}: the rule-presets markers are missing. Add the two marker lines where the list belongs.`);
    continue;
  }
  const next = text.slice(0, start) + render(locale) + text.slice(end + END.length);
  if (next === text) continue;
  if (check) failures.push(`${relative(root, path)}: the rule preset list is stale. Run \`node scripts/rule-presets.mjs\`.`);
  else writeFileSync(path, next);
}

if (failures.length > 0) {
  console.error(failures.join('\n'));
  process.exit(1);
}
console.log(check ? 'Rule preset lists are current.' : 'Rule preset lists written.');
