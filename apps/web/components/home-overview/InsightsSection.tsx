"use client";

import { useTranslations } from "next-intl";
import type { ReactNode } from "react";

import { Amount } from "@/components/ui/Amount";
import DataLoadError from "@/components/ui/DataLoadError";
import { Link } from "@/components/ui/Link";
import {
  RowsSkeleton,
  Section,
  SectionEmpty,
} from "@/components/ui/RuledSection";
import { transactionReportScopeHref } from "@/lib/account/transaction-report-scope";
import useInsights, { type Insight } from "@/lib/api/insights/useInsights";
import { cn } from "@/lib/utils";

const SEVERITY_TONE: Record<Insight["severity"], string> = {
  critical: "text-destructive-text",
  info: "text-success-text",
  warning: "text-warning-text",
};

/**
 * The home's deterministic insights: a category spending faster than its own normal, or a budget
 * on course to overrun. Nothing is generated by a model — the sentence is copy for the `type` and
 * `severity`, and the figures come from `facts`.
 *
 * Each card already carries its one link. `actions` is the seam for the "Ask the assistant" link
 * that will join it, so adding one does not reshape the card.
 */
export function InsightsSection() {
  const t = useTranslations("homeOverview.insights");
  const query = useInsights();
  const insights = query.data?.insights ?? [];

  if (query.isPending) {
    return (
      <Section id="insights-heading" title={t("title")} busy>
        <RowsSkeleton rows={2} />
      </Section>
    );
  }

  if (query.error) {
    return (
      <Section id="insights-heading" title={t("title")}>
        <DataLoadError
          error={query.error}
          onRetry={() => void query.refetch()}
        />
      </Section>
    );
  }

  if (insights.length === 0) {
    return (
      <Section id="insights-heading" title={t("title")}>
        <SectionEmpty title={t("empty.title")} body={t("empty.body")} />
      </Section>
    );
  }

  return (
    <Section id="insights-heading" title={t("title")}>
      <ul className="flex flex-col">
        {insights.map((insight) => (
          <InsightCard key={insight.id} insight={insight} />
        ))}
      </ul>
    </Section>
  );
}

function InsightCard({ insight }: { insight: Insight }) {
  const t = useTranslations("homeOverview.insights");
  const severity = t(`severity.${insight.severity}`);

  if (insight.type === "spending_vs_normal") {
    const facts = insight.facts;
    const percent = Math.round(Math.abs(Number(facts.deviationPercent)));
    const href = transactionReportScopeHref({
      accountKeys: [],
      categoryKeys: facts.categoryKeys.map(String),
      direction: "out",
      excludeNonSpending: true,
      excludeTransfers: true,
      fromDate: facts.fromDate,
      merchantKeys: [],
      statuses: ["BOOKED", "PENDING"],
      tagKeys: [],
      toDate: facts.toDate,
    });

    return (
      <InsightCardShell
        href={href}
        label={severity}
        linkLabel={t("spending.link")}
        severity={insight.severity}
      >
        <p className="text-foreground text-base font-medium">
          {t(`spending.${facts.direction}`, {
            category: facts.categoryName,
            percent,
          })}
        </p>
        <p className="text-muted-foreground text-sm">
          {t.rich("spending.figures", {
            baseline: () => (
              <Amount
                className="font-mono"
                currency={facts.currency}
                value={Number(facts.baselineAmount)}
              />
            ),
            current: () => (
              <Amount
                className="font-mono"
                currency={facts.currency}
                value={Number(facts.currentAmount)}
              />
            ),
          })}
        </p>
      </InsightCardShell>
    );
  }

  const facts = insight.facts;
  const category = facts.parentCategoryName
    ? `${facts.parentCategoryName} / ${facts.categoryName}`
    : facts.categoryName;
  const [year, month] = insight.period.split("-");
  const href = `/budgets/${facts.budgetKey}/${year}/${Number(month)}`;

  return (
    <InsightCardShell
      href={href}
      label={severity}
      linkLabel={t("budget.link")}
      severity={insight.severity}
    >
      <p className="text-foreground text-base font-medium">
        {t("budget.pace", { category })}
      </p>
      <p className="text-muted-foreground text-sm">
        {t.rich("budget.figures", {
          budgeted: () => (
            <Amount
              className="font-mono"
              currency={facts.currencyCode}
              value={Number(facts.amountBudgeted)}
            />
          ),
          projected: () => (
            <Amount
              className="font-mono"
              currency={facts.currencyCode}
              value={Number(facts.projectedAmount)}
            />
          ),
        })}
      </p>
    </InsightCardShell>
  );
}

function InsightCardShell({
  children,
  severity,
  label,
  href,
  linkLabel,
  actions,
}: {
  children: ReactNode;
  severity: Insight["severity"];
  label: string;
  href: string;
  linkLabel: string;
  /** Extra actions beside the link (the assistant link will live here). */
  actions?: ReactNode;
}) {
  return (
    <li className="border-border flex flex-col gap-2 border-b py-4 first:pt-0">
      <div className="flex items-start justify-between gap-4">
        <div className="flex min-w-0 flex-col gap-1">{children}</div>
        <span
          className={cn(
            "shrink-0 text-xs font-medium tracking-wide uppercase",
            SEVERITY_TONE[severity],
          )}
        >
          {label}
        </span>
      </div>
      <div className="flex flex-wrap items-center gap-x-4 gap-y-2">
        <Link
          href={href}
          className="text-foreground text-sm font-medium underline-offset-4 hover:underline"
        >
          {linkLabel}
        </Link>
        {actions}
      </div>
    </li>
  );
}
