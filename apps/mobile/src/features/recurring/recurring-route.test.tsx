import { act, render, waitFor } from '@testing-library/react-native'

import { ApiError } from '@/lib/api/errors'

import { RecurringRoute } from './recurring-route'
import { recurringSummaryFixture } from './test-fixtures'

const mockAccounts = jest.fn()
const mockItems = jest.fn()
const mockSummary = jest.fn()
const mockCategories = jest.fn()
const mockMutation = jest.fn()
const mockBlockAccess = jest.fn()
let mockScreenProps: Record<string, unknown>
jest.mock('expo-router', () => ({ useRouter: () => ({ replace: jest.fn() }) }))
jest.mock('@/components/providers/product-runtime-provider', () => ({ useProductRuntime: () => ({ blockAccess: mockBlockAccess }) }))
jest.mock('@/features/accounts/use-accounts', () => ({ useAccounts: () => mockAccounts() }))
jest.mock('@/features/categories/use-categories', () => ({ useCategories: () => mockCategories() }))
jest.mock('./use-recurring-items', () => ({ useRecurringItems: () => mockItems() }))
jest.mock('./use-recurring-mutations', () => ({ useRecurringMutations: () => mockMutation() }))
jest.mock('./use-recurring-summary', () => ({ useRecurringSummary: () => mockSummary() }))
jest.mock('./recurring-screen', () => ({ RecurringScreen: (props: { state: { status: string } }) => { mockScreenProps = props; const Native = jest.requireActual<typeof import('react-native')>('react-native'); return <Native.Text>{props.state.status}</Native.Text> } }))

const base = { isAccessTransition: false, isLoading: false, isRefreshFailure: false, isRefreshing: false, error: null, refetch: jest.fn() }
describe('RecurringRoute', () => {
  beforeEach(() => { mockAccounts.mockReset(); mockItems.mockReset(); mockSummary.mockReset(); mockBlockAccess.mockReset(); mockCategories.mockReturnValue({ ...base, data: { categories: [] }, isError: false }); mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync: jest.fn() }) })
  it('maps no-account separately from an empty recurring list', async () => {
    mockAccounts.mockReturnValue({ ...base, data: { accounts: [] } })
    mockItems.mockReturnValue({ ...base, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, data: recurringSummaryFixture })
    const view = await render(<RecurringRoute />)
    expect(view.getByText('no-account')).toBeOnTheScreen()
  })
  it('maps loaded and retained stale states', async () => {
    mockAccounts.mockReturnValue({ ...base, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, data: { items: [] }, isRefreshFailure: true })
    mockSummary.mockReturnValue({ ...base, data: recurringSummaryFixture })
    const view = await render(<RecurringRoute />)
    expect(view.getByText('refresh-error')).toBeOnTheScreen()
  })
  it('keeps demo, category ownership, network, and cancellation outcomes distinct', async () => {
    mockAccounts.mockReturnValue({ ...base, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, data: recurringSummaryFixture })
    const mutateAsync = jest.fn()
      .mockRejectedValueOnce(new ApiError('http', 404))
      .mockRejectedValueOnce(new ApiError('network'))
      .mockRejectedValueOnce(new ApiError('cancelled'))
      .mockRejectedValueOnce(new ApiError('demo-forbidden', 403))
    mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync })
    await render(<RecurringRoute />)
    const update = mockScreenProps.onUpdate as (id: number, metadata: { displayName: string }) => Promise<string>
    const confirm = mockScreenProps.onConfirm as (id: number) => Promise<string>
    await expect(update(7, { displayName: 'Rent' })).resolves.toBe('category')
    await expect(confirm(7)).resolves.toBe('network')
    await expect(confirm(7)).resolves.toBe('cancelled')
    await act(async () => { await expect(confirm(7)).resolves.toBe('demo') })
    await waitFor(() => expect(mockScreenProps.demoReadOnly).toBe(true))
    await expect((mockScreenProps.onConfirm as (id: number) => Promise<string>)(7)).resolves.toBe('demo')
    expect(mutateAsync).toHaveBeenCalledTimes(4)
  })
  it('wires onRestore to a restore mutation', async () => {
    mockAccounts.mockReturnValue({ ...base, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, data: recurringSummaryFixture })
    const mutateAsync = jest.fn().mockResolvedValue(undefined)
    mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync })
    await render(<RecurringRoute />)
    await expect((mockScreenProps.onRestore as (id: number) => Promise<string>)(7)).resolves.toBe('success')
    expect(mutateAsync).toHaveBeenCalledWith({ kind: 'restore', id: 7 })
  })
  it('transitions MFA errors without reporting an ordinary failure', async () => {
    mockAccounts.mockReturnValue({ ...base, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, data: recurringSummaryFixture })
    mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync: jest.fn().mockRejectedValue(new ApiError('mfa-required', 403)) })
    await render(<RecurringRoute />)
    await expect((mockScreenProps.onConfirm as (id: number) => Promise<string>)(7)).resolves.toBe('mfa')
    expect(mockBlockAccess).toHaveBeenCalledWith('mfa-required')
  })
  it('gates an ambiguous scan until a successful manual recurring refresh', async () => {
    const accountRefetch = jest.fn().mockResolvedValue({ isError: false })
    const itemRefetch = jest.fn().mockResolvedValueOnce({ isError: true }).mockResolvedValueOnce({ isError: false })
    const summaryRefetch = jest.fn().mockResolvedValue({ isError: false })
    mockAccounts.mockReturnValue({ ...base, refetch: accountRefetch, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, refetch: itemRefetch, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, refetch: summaryRefetch, data: recurringSummaryFixture })
    const mutateAsync = jest.fn().mockRejectedValue(new ApiError('network'))
    mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync })
    await render(<RecurringRoute />)
    await act(async () => { await expect((mockScreenProps.onScan as () => Promise<string>)()).resolves.toBe('unknown') })
    await waitFor(() => expect(mockScreenProps.scanNeedsRefresh).toBe(true))
    await expect((mockScreenProps.onScan as () => Promise<string>)()).resolves.toBe('unknown')
    expect(mutateAsync).toHaveBeenCalledTimes(1)
    await act(async () => { await (mockScreenProps.onRefresh as () => Promise<void>)() })
    expect(mockScreenProps.scanNeedsRefresh).toBe(true)
    await act(async () => { await (mockScreenProps.onRefresh as () => Promise<void>)() })
    await waitFor(() => expect(mockScreenProps.scanNeedsRefresh).toBe(false))
  })
  it('treats an invalid scan response as ambiguous and blocks every write until both recurring refreshes succeed', async () => {
    const accountRefetch = jest.fn().mockResolvedValue({ isError: false })
    const itemRefetch = jest.fn().mockResolvedValue({ isError: false })
    const summaryRefetch = jest.fn().mockResolvedValueOnce({ isError: true }).mockResolvedValueOnce({ isError: false })
    mockAccounts.mockReturnValue({ ...base, refetch: accountRefetch, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, refetch: itemRefetch, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, refetch: summaryRefetch, data: recurringSummaryFixture })
    const mutateAsync = jest.fn().mockRejectedValue(new ApiError('invalid-response'))
    mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync })
    await render(<RecurringRoute />)
    await act(async () => { await expect((mockScreenProps.onScan as () => Promise<string>)()).resolves.toBe('unknown') })
    await waitFor(() => expect(mockScreenProps.scanNeedsRefresh).toBe(true))
    await expect((mockScreenProps.onScan as () => Promise<string>)()).resolves.toBe('unknown')
    await expect((mockScreenProps.onConfirm as (id: number) => Promise<string>)(7)).resolves.toBe('unknown')
    await expect((mockScreenProps.onUpdate as (id: number, value: object) => Promise<string>)(7, { displayName: 'Rent' })).resolves.toBe('unknown')
    expect(mutateAsync).toHaveBeenCalledTimes(1)
    await act(async () => { await (mockScreenProps.onRefresh as () => Promise<void>)() })
    expect(mockScreenProps.scanNeedsRefresh).toBe(true)
    await act(async () => { await (mockScreenProps.onRefresh as () => Promise<void>)() })
    await waitFor(() => expect(mockScreenProps.scanNeedsRefresh).toBe(false))
  })
  it('keeps scan access, MFA, cancellation, demo, and general failures distinct', async () => {
    mockAccounts.mockReturnValue({ ...base, data: { accounts: [{ accountKey: 2, accountName: 'Daily account' }] } })
    mockItems.mockReturnValue({ ...base, data: { items: [] } })
    mockSummary.mockReturnValue({ ...base, data: recurringSummaryFixture })
    const mutateAsync = jest.fn()
      .mockRejectedValueOnce(new ApiError('http', 403))
      .mockRejectedValueOnce(new ApiError('mfa-required', 401))
      .mockRejectedValueOnce(new ApiError('cancelled'))
      .mockRejectedValueOnce(new ApiError('http', 500))
      .mockRejectedValueOnce(new ApiError('demo-forbidden', 403))
    mockMutation.mockReturnValue({ isPending: false, variables: undefined, mutateAsync })
    await render(<RecurringRoute />)
    const scan = () => (mockScreenProps.onScan as () => Promise<string>)()
    await expect(scan()).resolves.toBe('access')
    await expect(scan()).resolves.toBe('mfa')
    expect(mockBlockAccess).toHaveBeenCalledWith('mfa-required')
    await expect(scan()).resolves.toBe('cancelled')
    await expect(scan()).resolves.toBe('error')
    await act(async () => { await expect(scan()).resolves.toBe('demo') })
    await waitFor(() => expect(mockScreenProps.demoReadOnly).toBe(true))
  })
})
