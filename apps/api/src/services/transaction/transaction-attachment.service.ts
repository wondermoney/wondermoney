import { QueryOrder } from '@mikro-orm/core';
import { v4 as uuidv4 } from 'uuid';

import { DI } from '@app/app';
import { Appuser } from '@entity/Appuser';
import { Tenant } from '@entity/Tenant';
import { Transaction } from '@entity/Transaction';
import { TransactionAttachment } from '@entity/TransactionAttachment';
import s3Service from '@service/storage/s3';
import { getRef } from '@utils/em-helpers';
import { BadRequestError, NotFoundError, ServiceUnavailableError } from '@utils/errors';
import { extensionForContentType, sniffFileContentType, SUPPORTED_FILE_CONTENT_TYPES, type SupportedFileContentType } from '@utils/file-signature';
import logger from '@utils/logger';

/** Ten files is what one purchase's paperwork plausibly needs; more is a bulk import in disguise. */
export const TRANSACTION_ATTACHMENT_MAX_FILES = 10;
export const TRANSACTION_ATTACHMENT_MAX_SIZE_BYTES = 10 * 1024 * 1024;
/** A browser PUTs within this window; long enough for a slow phone upload. */
export const TRANSACTION_ATTACHMENT_UPLOAD_URL_TTL_SECONDS = 15 * 60;
/** Downloads are short-lived: a leaked URL stops working in minutes, not days. */
export const TRANSACTION_ATTACHMENT_VIEW_URL_TTL_SECONDS = 5 * 60;
export const TRANSACTION_ATTACHMENT_STORAGE_PREFIX = 'wmattachments';

export interface AttachmentUploadUrl {
  expiresInSeconds: number;
  key: string;
  presignedUrl: string;
  uploadHeaders: Record<string, string>;
  uploadMethod: 'PUT';
}

export interface AttachmentUploadUrlInput {
  contentType: string;
  fileName: string;
  sizeBytes: number;
  tenantKey: number;
  transactionKey: number;
}

export interface ConfirmAttachmentInput {
  fileName: string;
  key: string;
  tenantKey: number;
  transactionKey: number;
  uploadedByAppuserKey: number;
  /**
   * The key was generated by the server (the OCR receipt copy), not sent by a client, so the
   * client-key prefix rule does not apply. It is still read from our own store only.
   */
  trustedKey?: boolean;
}

export interface TransactionAttachmentDto {
  contentType: string;
  createdAt: string;
  fileName: string;
  sizeBytes: number;
  transactionAttachmentKey: number;
  /** A short-lived presigned GET link; never a public object URL. */
  url: string;
}

/** The declared type is a hint; the bytes decide the stored type. Accept the HEIF/HEIC and JPG aliases. */
const ALLOWED_CONTENT_TYPES = new Set<string>([...SUPPORTED_FILE_CONTENT_TYPES, 'image/heif', 'image/jpg']);

function assertStorageEnabled(): void {
  if (!s3Service.isEnabled()) throw new ServiceUnavailableError('File storage is not configured');
}

/** The file name as it is safe to store and echo back: one path segment, no control characters. */
export function sanitizeAttachmentFileName(fileName: string): string {
  const base = fileName.split(/[\\/]/u).pop() ?? '';
  // eslint-disable-next-line no-control-regex
  const cleaned = base.replace(/[\u0000-\u001f\u007f"]/gu, '').trim();
  return cleaned.slice(0, 200) || 'attachment';
}

/**
 * `wmattachments/<tenant>/<random id>/<file name>`.
 *
 * The tenant segment makes a key self-describing and lets the confirm step reject a key from
 * another household before touching the store; the random id makes keys unguessable and keeps two
 * files with the same name apart.
 */
export function buildAttachmentStorageKey(tenantKey: number, fileName: string): string {
  return `${TRANSACTION_ATTACHMENT_STORAGE_PREFIX}/${tenantKey}/${uuidv4()}/${sanitizeAttachmentFileName(fileName)}`;
}

/** Whether `key` is an attachment key that belongs to `tenantKey` (and is not a traversal attempt). */
export function isAttachmentStorageKeyForTenant(key: string, tenantKey: number): boolean {
  if (key.length === 0 || key.length > 512) return false;
  if (key.includes('..') || key.startsWith('/') || key.includes('\\')) return false;
  return key.startsWith(`${TRANSACTION_ATTACHMENT_STORAGE_PREFIX}/${tenantKey}/`);
}

function assertDeclaredContentType(contentType: string): void {
  if (!ALLOWED_CONTENT_TYPES.has(contentType)) {
    throw new BadRequestError('Only JPEG, PNG, WebP, HEIC and PDF files are supported.');
  }
}

function assertDeclaredSize(sizeBytes: number): void {
  if (!Number.isSafeInteger(sizeBytes) || sizeBytes <= 0) throw new BadRequestError('The file is empty.');
  if (sizeBytes > TRANSACTION_ATTACHMENT_MAX_SIZE_BYTES) throw new BadRequestError('Each file must be 10 MB or smaller.');
}

/**
 * A presigned PUT for one new attachment. The declared size and type are checked here and again,
 * from the bytes themselves, when the upload is confirmed.
 */
export async function createAttachmentUploadUrl(input: AttachmentUploadUrlInput): Promise<AttachmentUploadUrl> {
  assertStorageEnabled();
  await findTransaction(input.transactionKey, input.tenantKey);
  assertDeclaredContentType(input.contentType);
  assertDeclaredSize(input.sizeBytes);

  const key = buildAttachmentStorageKey(input.tenantKey, input.fileName);
  const presignedUrl = await s3Service.generatePresignedUploadUrl(s3Service.getFilesBucketName(), key, {
    contentLength: input.sizeBytes,
    contentType: input.contentType,
    expiresInSeconds: TRANSACTION_ATTACHMENT_UPLOAD_URL_TTL_SECONDS,
  });
  return {
    expiresInSeconds: TRANSACTION_ATTACHMENT_UPLOAD_URL_TTL_SECONDS,
    key,
    presignedUrl,
    uploadHeaders: { 'Content-Type': input.contentType },
    uploadMethod: 'PUT',
  };
}

async function findTransaction(transactionKey: number, tenantKey: number): Promise<Transaction> {
  const transaction = await DI.em.findOne(Transaction, { deletedAt: undefined, tenantKey: { tenantKey }, transactionKey });
  if (!transaction) throw new NotFoundError('Transaction not found');
  return transaction;
}

async function liveAttachmentCount(transactionKey: number, tenantKey: number): Promise<number> {
  return DI.em.count(TransactionAttachment, { deletedAt: undefined, tenantKey: { tenantKey }, transactionKey: { transactionKey } });
}

/**
 * Confirms an upload that is already in the store: its real size and its bytes decide whether it
 * is accepted, and the row records the sniffed type. A refused object is removed from the store.
 */
export async function confirmAttachment(input: ConfirmAttachmentInput): Promise<TransactionAttachmentDto> {
  assertStorageEnabled();
  await findTransaction(input.transactionKey, input.tenantKey);

  if (!input.trustedKey && !isAttachmentStorageKeyForTenant(input.key, input.tenantKey)) {
    throw new BadRequestError('Invalid attachment key');
  }
  if ((await liveAttachmentCount(input.transactionKey, input.tenantKey)) >= TRANSACTION_ATTACHMENT_MAX_FILES) {
    throw new BadRequestError(`A transaction can have at most ${TRANSACTION_ATTACHMENT_MAX_FILES} attachments.`);
  }

  const bucket = s3Service.getFilesBucketName();
  const sizeBytes = await s3Service.getObjectSize(bucket, input.key);
  if (sizeBytes === undefined || sizeBytes <= 0) {
    throw new BadRequestError('The uploaded file could not be found.');
  }
  if (sizeBytes > TRANSACTION_ATTACHMENT_MAX_SIZE_BYTES) {
    await removeStoredObject(bucket, input.key);
    throw new BadRequestError('Each file must be 10 MB or smaller.');
  }

  const bytes = await s3Service.getObjectBuffer(bucket, input.key);
  const contentType = sniffFileContentType(bytes);
  if (!contentType) {
    await removeStoredObject(bucket, input.key);
    throw new BadRequestError('Only JPEG, PNG, WebP, HEIC and PDF files are supported.');
  }

  const fileName = withExtension(sanitizeAttachmentFileName(input.fileName), contentType);
  const attachment = DI.em.create(TransactionAttachment, {
    contentType,
    fileName,
    sizeBytes,
    storageKey: input.key,
    tenantKey: getRef(DI.em, Tenant, input.tenantKey),
    transactionKey: getRef(DI.em, Transaction, input.transactionKey),
    uploadedByAppuserKey: getRef(DI.em, Appuser, input.uploadedByAppuserKey),
  }, { partial: true });
  await DI.em.persist(attachment).flush();

  return toDto(attachment);
}

/** Removes an object the request will not keep; a store hiccup is logged, not surfaced. */
async function removeStoredObject(bucket: string, key: string): Promise<void> {
  try {
    await s3Service.deleteObject(bucket, key);
  } catch (error) {
    logger.warn({ error, key }, 'Could not remove an attachment object');
  }
}

/** A name with no extension gets one from the sniffed type, so a saved file opens as what it is. */

function withExtension(fileName: string, contentType: SupportedFileContentType): string {
  if (/\.[a-z0-9]{2,5}$/iu.test(fileName)) return fileName;
  return `${fileName}.${extensionForContentType(contentType)}`;
}

/** The transaction's live attachments, oldest first, each with its own short-lived view URL. */
export async function listAttachments(transactionKey: number, tenantKey: number): Promise<TransactionAttachmentDto[]> {
  assertStorageEnabled();
  await findTransaction(transactionKey, tenantKey);

  const attachments = await DI.em.find(
    TransactionAttachment,
    { deletedAt: undefined, tenantKey: { tenantKey }, transactionKey: { transactionKey } },
    { orderBy: { createdAt: QueryOrder.ASC } },
  );
  return Promise.all(attachments.map(toDto));
}

/** Soft-deletes the row and removes the object. The row is the authority: the file is unreachable either way. */
export async function deleteAttachment(transactionKey: number, tenantKey: number, attachmentId: number): Promise<void> {
  assertStorageEnabled();
  await findTransaction(transactionKey, tenantKey);

  const attachment = await DI.em.findOne(TransactionAttachment, {
    deletedAt: undefined,
    tenantKey: { tenantKey },
    transactionAttachmentKey: attachmentId,
    transactionKey: { transactionKey },
  });
  if (!attachment) throw new NotFoundError('Attachment not found');

  attachment.deletedAt = new Date();
  await DI.em.persist(attachment).flush();
  await removeStoredObject(s3Service.getFilesBucketName(), attachment.storageKey);
}

/**
 * Links a receipt the OCR flow already stored to the transaction it created. Best-effort: the
 * transaction exists and must not fail because its image could not be attached.
 */
export async function linkReceiptAttachment(input: { key: string; tenantKey: number; transactionKey: number; uploadedByAppuserKey: number }): Promise<void> {
  if (!s3Service.isEnabled()) return;
  try {
    await confirmAttachment({ fileName: 'receipt', key: input.key, tenantKey: input.tenantKey, transactionKey: input.transactionKey, trustedKey: true, uploadedByAppuserKey: input.uploadedByAppuserKey });
  } catch (error) {
    logger.warn({ error, key: input.key, transactionKey: input.transactionKey }, 'Could not link the OCR receipt to its transaction');
  }
}

async function toDto(attachment: TransactionAttachment): Promise<TransactionAttachmentDto> {
  const url = await s3Service.generatePresignedViewUrl(
    s3Service.getFilesBucketName(),
    attachment.storageKey,
    attachment.contentType,
    TRANSACTION_ATTACHMENT_VIEW_URL_TTL_SECONDS,
  );
  return {
    contentType: attachment.contentType,
    createdAt: attachment.createdAt.toISOString(),
    fileName: attachment.fileName,
    sizeBytes: attachment.sizeBytes,
    transactionAttachmentKey: attachment.transactionAttachmentKey,
    url,
  };
}
